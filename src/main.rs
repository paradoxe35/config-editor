const JSON_SAMPLE: &str = "{\n  \"listen\": 7835,\n  \"public_address\": \"tunnel.example.com\",\n  \"insecure_plaintext\": false\n}\n";
const TOML_SAMPLE: &str = "# Burrow server configuration\nlisten = 7835\npublic_address = \"tunnel.example.com\"\ninsecure_plaintext = false\n";
const HCL_SAMPLE: &str = "# Burrow server configuration\nlisten = 7835\npublic_address = \"tunnel.example.com\"\ninsecure_plaintext = false\n";
const XML_SAMPLE: &str = "<listen>7835</listen>\n<public_address>tunnel.example.com</public_address>\n<insecure_plaintext>false</insecure_plaintext>\n<clients>\n  <acme>\n    <secret>c2VjcmV0LWZvci1hY21l</secret>\n  </acme>\n</clients>\n";
const SCHEMA: &str = include_str!("../schema.json");
const HELP_SCHEMA: &str =
    include_str!("../crates/config-editor-leptos/tests/fixtures/schema-help.schema.json");
const PROTECTED_SCHEMA: &str =
    include_str!("../crates/config-editor-leptos/tests/fixtures/protected.schema.json");

/// The protected-fields fixture's document in `language`.
fn protected_sample(language: Language) -> &'static str {
    match language.label() {
        "JSON" => {
            "{\n  \"id\": \"srv-42\",\n  \"name\": \"edge\",\n  \"listen\": 7835,\n  \"limits\": {\n    \"max\": 10,\n    \"burst\": 20\n  },\n  \"tls\": {\n    \"cert\": \"/etc/edge.pem\",\n    \"key\": \"«secret 3f2a»\",\n    \"pin\": \"«secret 0b1c»\"\n  }\n}\n"
        }
        "TOML" => {
            "id = \"srv-42\"\nname = \"edge\"\nlisten = 7835\n\n[limits]\nmax = 10\nburst = 20\n\n[tls]\ncert = \"/etc/edge.pem\"\nkey = \"«secret 3f2a»\"\npin = \"«secret 0b1c»\"\n"
        }
        "HCL" => {
            "id = \"srv-42\"\nname = \"edge\"\nlisten = 7835\n\nlimits {\n  max = 10\n  burst = 20\n}\n\ntls {\n  cert = \"/etc/edge.pem\"\n  key = \"«secret 3f2a»\"\n  pin = \"«secret 0b1c»\"\n}\n"
        }
        "XML" => {
            "<id>srv-42</id>\n<name>edge</name>\n<listen>7835</listen>\n<limits>\n  <max>10</max>\n  <burst>20</burst>\n</limits>\n<tls>\n  <cert>/etc/edge.pem</cert>\n  <key>«secret 3f2a»</key>\n  <pin>«secret 0b1c»</pin>\n</tls>\n"
        }
        _ => {
            "id: srv-42\nname: edge\nlisten: 7835\nlimits:\n  max: 10\n  burst: 20\ntls:\n  cert: /etc/edge.pem\n  key: «secret 3f2a»\n  pin: «secret 0b1c»\n"
        }
    }
}

/// The short and the large (~2000-line) sample of a language; the large ones
/// are generated by `samples/generate.py` into the editor crate's test fixtures.
fn samples(language: Language) -> (&'static str, &'static str) {
    match language.label() {
        "JSON" => (
            JSON_SAMPLE,
            include_str!("../crates/config-editor-leptos/tests/fixtures/samples/burrow.large.json"),
        ),
        "TOML" => (
            TOML_SAMPLE,
            include_str!("../crates/config-editor-leptos/tests/fixtures/samples/burrow.large.toml"),
        ),
        "HCL" => (
            HCL_SAMPLE,
            include_str!("../crates/config-editor-leptos/tests/fixtures/samples/burrow.large.hcl"),
        ),
        "XML" => (
            XML_SAMPLE,
            include_str!("../crates/config-editor-leptos/tests/fixtures/samples/burrow.large.xml"),
        ),
        _ => (
            YAML_SAMPLE,
            include_str!("../crates/config-editor-leptos/tests/fixtures/samples/burrow.large.yaml"),
        ),
    }
}

/// The text the page left in `window.configEditorSample` (`?sample=page`),
/// kept for the page's lifetime.
fn page_sample() -> Option<&'static str> {
    let window = web_sys::window()?;
    let value = web_sys::js_sys::Reflect::get(&window, &"configEditorSample".into()).ok()?;
    Some(value.as_string()?.leak())
}

/// The server's version after another client changed it: the first number
/// goes up by one (`listen: 7835` becomes `7836`), else a line is added.
fn changed_on_server(text: &str) -> String {
    let Some(start) = text.find(|c: char| c.is_ascii_digit()) else {
        return format!("{text}\n");
    };
    let end = text[start..]
        .find(|c: char| !c.is_ascii_digit())
        .map_or(text.len(), |length| start + length);
    let number: u64 = text[start..end].parse().unwrap_or(0);
    format!("{}{}{}", &text[..start], number + 1, &text[end..])
}

/// The page's query flags (`language=json`, `sample=large`, `readonly`).
fn query_flags() -> Vec<String> {
    web_sys::window()
        .and_then(|window| window.location().search().ok())
        .unwrap_or_default()
        .trim_start_matches('?')
        .split('&')
        .filter(|pair| !pair.is_empty())
        .map(str::to_string)
        .collect()
}

fn query_value(flags: &[String], name: &str) -> Option<String> {
    let prefix = format!("{name}=");
    flags
        .iter()
        .find_map(|pair| pair.strip_prefix(&prefix).map(str::to_string))
}

/// The query with `name=value` replacing that flag (an empty value removes
/// it), keeping the others.
fn query_with(name: &str, value: &str) -> String {
    let prefix = format!("{name}=");
    let mut flags: Vec<String> = query_flags()
        .into_iter()
        .filter(|pair| !pair.starts_with(&prefix))
        .collect();
    if !value.is_empty() {
        flags.push(format!("{name}={value}"));
    }
    format!("?{}", flags.join("&"))
}

/// Reloads the demo with `name=value` (for choices that pick a new document).
fn navigate_with(name: &str, value: &str) {
    if let Some(window) = web_sys::window() {
        let _ = window.location().set_search(&query_with(name, value));
    }
}

/// Records `name=value` in the URL without reloading (for live choices).
fn remember(name: &str, value: &str) {
    if let Some(history) = web_sys::window().and_then(|window| window.history().ok()) {
        let _ = history.replace_state_with_url(
            &web_sys::wasm_bindgen::JsValue::NULL,
            "",
            Some(&query_with(name, value)),
        );
    }
}

/// The URL value of a language: its preferred extension.
fn key(language: Language) -> &'static str {
    language.extensions()[0]
}

fn main() {
    console_error_panic_hook::set_once();
    let flags = query_flags();
    if let Some(mode) = flags
        .iter()
        .find(|pair| *pair == "documents" || pair.starts_with("documents="))
    {
        let many = mode == "documents=many";
        leptos::mount::mount_to_body(move || documents_demo::view(many));
        return;
    }
    leptos::mount::mount_to_body(|| {
        let flags = query_flags();
        let language = query_value(&flags, "language")
            .and_then(|name| name.parse::<Language>().ok())
            .unwrap_or_default();
        // Live: switching converts the open document in place.
        let edit_as = RwSignal::new(
            query_value(&flags, "edit")
                .and_then(|name| name.parse::<Language>().ok())
                .filter(|edit| *edit != language),
        );
        let sample_flag = query_value(&flags, "sample");
        let large_sample = matches!(sample_flag.as_deref(), Some("large" | "page"));
        let (small, large) = samples(language);
        let sample = match sample_flag.as_deref() {
            Some("page") => page_sample().unwrap_or(large),
            Some("large") => large,
            _ => small,
        };
        let file_name = format!(
            "burrow{}.{}",
            if large_sample { ".large" } else { "" },
            key(language)
        );
        let read_only = RwSignal::new(
            flags
                .iter()
                .any(|pair| pair == "readonly" || pair == "readonly=1"),
        );
        // Every setting switches live from the panel below the editor.
        let settings = RwSignal::new(EditorSettings {
            show_footer: true,
            folding: query_value(&flags, "folding").as_deref() != Some("0"),
            ..EditorSettings::default()
        });
        let theme = Signal::derive(move || settings.with(|settings| settings.theme));
        let (schema, sample) = match query_value(&flags, "schema").as_deref() {
            Some("help") => (HELP_SCHEMA, ""),
            Some("protected") => (PROTECTED_SCHEMA, protected_sample(language)),
            _ => (SCHEMA, sample),
        };
        // Fields the host locks on top of the schema's (`lock=/name,/listen`).
        let locked: Vec<FieldPath> = query_value(&flags, "lock")
            .map(|paths| {
                paths
                    .split(',')
                    .filter(|path| !path.is_empty())
                    .map(|path| FieldPath::from(path.replace("%2F", "/")))
                    .collect()
            })
            .unwrap_or_default();
        let schema_warnings = RwSignal::new(Vec::<String>::new());

        let baseline = RwSignal::new(sample.to_string());
        let saved = RwSignal::new(sample.to_string());
        // Host-controlled editing: what was saved, whether there are unsaved
        // edits, and the baseline conflicts seen (for the e2e tests).
        let saves = RwSignal::new(0usize);
        let dirty = RwSignal::new(false);
        let conflicts = RwSignal::new(Vec::<String>::new());
        let server_change = move |_| {
            // Another client saved: the server's version moves on.
            baseline.update(|text| *text = changed_on_server(text));
        };
        let save = move |request: SaveRequest| {
            saved.set(request.text.clone());
            baseline.set(request.text);
            saves.update(|count| *count += 1);
        };
        // The language on screen, as the editor reports it: the file's own
        // until a switch completes (one that waits keeps showing the file's
        // language, with the reason on the value in the way), and back after
        // an undo across a switch. The picker follows it too.
        let editing = RwSignal::new(language);
        let follow_editing = move |edit: Language| {
            editing.set(edit);
            let chosen = (edit != language).then_some(edit);
            if edit_as.get_untracked() != chosen {
                edit_as.set(chosen);
                remember("edit", chosen.map_or("", key));
            }
        };
        let shown = move || editing.get();
        let toolbar_file = {
            let file_name = file_name.clone();
            move || match editing.get() {
                edit if edit != language => format!("{file_name} (editing as {edit})"),
                _ => file_name.clone(),
            }
        };

        view! {
            <div
                class="config-editor demo"
                data-theme=move || theme.get().css_family()
                data-color-theme=move || theme.get().as_str()
            >
                <ConfigEditorToolbar class="demo__toolbar" theme=theme>
                    <div class="config-editor__file">
                        <span class="config-editor__file-icon">{move || shown().file_icon()}</span>
                        <span>{toolbar_file}</span>
                    </div>
                    <label class="demo__picker">
                        "File"
                        <select
                            class="demo__select demo__language-select"
                            aria-label="Stored config language"
                            on:change=move |event| navigate_with("language", &event_target_value(&event))
                        >
                            {Language::ALL
                                .iter()
                                .copied()
                                .map(|option| view! {
                                    <option value=key(option) selected=option == language>
                                        {option.label()}
                                    </option>
                                })
                                .collect_view()}
                        </select>
                    </label>
                    <label class="demo__picker">
                        "Edit as"
                        <select
                            class="demo__select demo__edit-select"
                            aria-label="Editing language"
                            prop:value=move || edit_as.get().map_or("", key)
                            on:change=move |event| {
                                let value = event_target_value(&event);
                                edit_as.set(value.parse::<Language>().ok());
                                remember("edit", &value);
                            }
                        >
                            <option value="" selected=edit_as.get_untracked().is_none()>"Same"</option>
                            {Language::ALL
                                .iter()
                                .copied()
                                .filter(|option| *option != language)
                                .map(|option| view! {
                                    <option value=key(option) selected=edit_as.get_untracked() == Some(option)>
                                        {option.label()}
                                    </option>
                                })
                                .collect_view()}
                        </select>
                    </label>
                    <label class="demo__picker">
                        "Sample"
                        <select
                            class="demo__select demo__sample-select"
                            aria-label="Sample config"
                            on:change=move |event| navigate_with("sample", &event_target_value(&event))
                        >
                            <option value="small" selected=!large_sample>"Short"</option>
                            <option value="large" selected=large_sample>"Large (~2000 lines)"</option>
                        </select>
                    </label>
                    <label class="demo__picker">
                        "Theme"
                        <select
                            class="demo__select demo__theme-select"
                            aria-label="Editor theme"
                            on:change=move |event| {
                                let theme = event_target_value(&event).parse().unwrap_or_default();
                                settings.update(|settings| settings.theme = theme);
                            }
                        >
                            {EditorTheme::ALL
                                .iter()
                                .map(|option| view! {
                                    <option value=option.as_str()>{option.label()}</option>
                                })
                                .collect_view()}
                        </select>
                    </label>
                    <button
                        class="config-editor__action-button"
                        type="button"
                        disabled=move || baseline.with(|baseline| saved.with(|saved| baseline == saved))
                        on:click=move |_| baseline.set(saved.get())
                    >
                        "Apply changes"
                    </button>
                    <SettingsPanel settings=settings />
                </ConfigEditorToolbar>
                <ConfigEditor
                    language=language
                    edit_as=edit_as
                    initial_value=sample
                    baseline=baseline
                    value=saved
                    on_change=move |text| saved.set(text)
                    on_save=save
                    on_dirty_change=move |now| dirty.set(now)
                    on_baseline_conflict=move |event| conflicts.update(|all| all.push(format!("{event:?}")))
                    on_edit_as_change=follow_editing
                    schema=schema
                    on_schema_warning=move |warning| schema_warnings.update(|all| all.push(warning))
                    file_name=file_name
                    settings=settings
                    read_only=read_only
                    read_only_paths=locked
                />
                <ul class="demo__schema-warnings">
                    {move || schema_warnings.get().into_iter().map(|warning| view! { <li>{warning}</li> }).collect_view()}
                </ul>
                <details class="demo__output">
                    <summary class="demo__summary">
                        <span>{format!("Saved value ({language}) — what on_change sends the host")}</span>
                        <span class="demo__host">
                            <label class="demo__picker">
                                <input
                                    type="checkbox"
                                    class="demo__read-only"
                                    prop:checked=move || read_only.get()
                                    on:change=move |event| read_only.set(event_target_checked(&event))
                                />
                                "Read-only"
                            </label>
                            <button class="demo__button demo__server-change" type="button" on:click=server_change>
                                "Server change"
                            </button>
                            <button
                                class="demo__button demo__host-edit"
                                type="button"
                                on:click=move |_| saved.update(|text| *text = changed_on_server(text))
                            >
                                "Host edit"
                            </button>
                            <span class="demo__host-status" title="Unsaved changes" data-dirty=move || dirty.get().to_string() data-saves=move || saves.get().to_string() data-conflicts=move || conflicts.get().join(",")>
                                {move || if dirty.get() { "●" } else { "" }}
                            </span>
                        </span>
                    </summary>
                    <pre class="demo__output-text">{move || saved.get()}</pre>
                </details>
            </div>
        }
    })
}
