//! Demo host for `config-editor-leptos`: the same burrow server config in every
//! language, switchable from the toolbar (all state lives in the URL so a
//! reload keeps it):
//!
//! - `?language=xml` — the language the host stores (YAML by default);
//! - `?edit=hcl` — edit it as another language (`edit_as`);
//! - `?sample=large` — the ~2000-line config instead of the short one;
//! - `?readonly` — view mode;
//! - `?schema=help` — the schema-help fixture (deprecated keys, docs links,
//!   documented values) instead of the burrow schema, with its warnings
//!   listed under the editor.

use config_editor_leptos::{ConfigEditor, ConfigEditorToolbar, EditorTheme, Language};
use leptos::prelude::*;

const YAML_SAMPLE: &str = "# Burrow server configuration\nlisten: 7835\npublic_address: tunnel.example.com\ninsecure_plaintext: false\n";
const JSON_SAMPLE: &str = "{\n  \"listen\": 7835,\n  \"public_address\": \"tunnel.example.com\",\n  \"insecure_plaintext\": false\n}\n";
const TOML_SAMPLE: &str = "# Burrow server configuration\nlisten = 7835\npublic_address = \"tunnel.example.com\"\ninsecure_plaintext = false\n";
const HCL_SAMPLE: &str = "# Burrow server configuration\nlisten = 7835\npublic_address = \"tunnel.example.com\"\ninsecure_plaintext = false\n";
const XML_SAMPLE: &str = "<listen>7835</listen>\n<public_address>tunnel.example.com</public_address>\n<insecure_plaintext>false</insecure_plaintext>\n<clients>\n  <acme>\n    <secret>c2VjcmV0LWZvci1hY21l</secret>\n  </acme>\n</clients>\n";
const SCHEMA: &str = include_str!("../schema.json");
const HELP_SCHEMA: &str =
    include_str!("../crates/config-editor-leptos/tests/fixtures/schema-help.schema.json");

/// The short and the large (~2000-line) sample of a language; the large ones
/// are generated by `samples/generate.py` into the editor crate's test fixtures.
fn samples(language: Language) -> (&'static str, &'static str) {
    match language.label() {
        "JSON" => (
            JSON_SAMPLE,
            include_str!("../crates/config-editor-leptos/tests/fixtures/samples/burrow.large.json"),
        ),
        "TOML" => (
            TOML_SAMPLE,
            include_str!("../crates/config-editor-leptos/tests/fixtures/samples/burrow.large.toml"),
        ),
        "HCL" => (
            HCL_SAMPLE,
            include_str!("../crates/config-editor-leptos/tests/fixtures/samples/burrow.large.hcl"),
        ),
        "XML" => (
            XML_SAMPLE,
            include_str!("../crates/config-editor-leptos/tests/fixtures/samples/burrow.large.xml"),
        ),
        _ => (
            YAML_SAMPLE,
            include_str!("../crates/config-editor-leptos/tests/fixtures/samples/burrow.large.yaml"),
        ),
    }
}

/// The page's query flags (`language=json`, `sample=large`, `readonly`).
fn query_flags() -> Vec<String> {
    web_sys::window()
        .and_then(|window| window.location().search().ok())
        .unwrap_or_default()
        .trim_start_matches('?')
        .split('&')
        .filter(|pair| !pair.is_empty())
        .map(str::to_string)
        .collect()
}

fn query_value(flags: &[String], name: &str) -> Option<String> {
    let prefix = format!("{name}=");
    flags
        .iter()
        .find_map(|pair| pair.strip_prefix(&prefix).map(str::to_string))
}

/// The query with `name=value` replacing that flag (an empty value removes
/// it), keeping the others.
fn query_with(name: &str, value: &str) -> String {
    let prefix = format!("{name}=");
    let mut flags: Vec<String> = query_flags()
        .into_iter()
        .filter(|pair| !pair.starts_with(&prefix))
        .collect();
    if !value.is_empty() {
        flags.push(format!("{name}={value}"));
    }
    format!("?{}", flags.join("&"))
}

/// Reloads the demo with `name=value` (for choices that pick a new document).
fn navigate_with(name: &str, value: &str) {
    if let Some(window) = web_sys::window() {
        let _ = window.location().set_search(&query_with(name, value));
    }
}

/// Records `name=value` in the URL without reloading (for live choices).
fn remember(name: &str, value: &str) {
    if let Some(history) = web_sys::window().and_then(|window| window.history().ok()) {
        let _ = history.replace_state_with_url(
            &web_sys::wasm_bindgen::JsValue::NULL,
            "",
            Some(&query_with(name, value)),
        );
    }
}

/// The URL value of a language: its preferred extension.
fn key(language: Language) -> &'static str {
    language.extensions()[0]
}

fn main() {
    console_error_panic_hook::set_once();
    leptos::mount::mount_to_body(|| {
        let flags = query_flags();
        let language = query_value(&flags, "language")
            .and_then(|name| name.parse::<Language>().ok())
            .unwrap_or_default();
        // Live: switching converts the open document in place.
        let edit_as = RwSignal::new(
            query_value(&flags, "edit")
                .and_then(|name| name.parse::<Language>().ok())
                .filter(|edit| *edit != language),
        );
        let large_sample = query_value(&flags, "sample").as_deref() == Some("large");
        let (small, large) = samples(language);
        let sample = if large_sample { large } else { small };
        let file_name = format!(
            "burrow{}.{}",
            if large_sample { ".large" } else { "" },
            key(language)
        );
        let read_only = flags
            .iter()
            .any(|pair| pair == "readonly" || pair == "readonly=1");
        let help_schema = query_value(&flags, "schema").as_deref() == Some("help");
        let (schema, sample) = if help_schema {
            (HELP_SCHEMA, "")
        } else {
            (SCHEMA, sample)
        };
        let schema_warnings = RwSignal::new(Vec::<String>::new());

        let baseline = RwSignal::new(sample.to_string());
        let saved = RwSignal::new(sample.to_string());
        let theme = RwSignal::new(EditorTheme::VsCodeDark);
        // What the editor shows, which lags `edit_as` while a switch waits.
        let editing = RwSignal::new(edit_as.get_untracked().unwrap_or(language));
        let shown = move || editing.get();
        let toolbar_file = {
            let file_name = file_name.clone();
            move || match editing.get() {
                edit if edit != language => format!("{file_name} (editing as {edit})"),
                _ => file_name.clone(),
            }
        };

        view! {
            <div
                class="config-editor demo"
                data-theme=move || theme.get().css_family()
                data-color-theme=move || theme.get().as_str()
            >
                <ConfigEditorToolbar class="demo__toolbar" theme=theme>
                    <div class="config-editor__file">
                        <span class="config-editor__file-icon">{move || shown().file_icon()}</span>
                        <span>{toolbar_file}</span>
                    </div>
                    <label class="demo__picker">
                        "File"
                        <select
                            class="demo__select demo__language-select"
                            aria-label="Stored config language"
                            on:change=move |event| navigate_with("language", &event_target_value(&event))
                        >
                            {Language::ALL
                                .iter()
                                .copied()
                                .map(|option| view! {
                                    <option value=key(option) selected=option == language>
                                        {option.label()}
                                    </option>
                                })
                                .collect_view()}
                        </select>
                    </label>
                    <label class="demo__picker">
                        "Edit as"
                        <select
                            class="demo__select demo__edit-select"
                            aria-label="Editing language"
                            on:change=move |event| {
                                let value = event_target_value(&event);
                                edit_as.set(value.parse::<Language>().ok());
                                remember("edit", &value);
                            }
                        >
                            <option value="" selected=edit_as.get_untracked().is_none()>"Same"</option>
                            {Language::ALL
                                .iter()
                                .copied()
                                .filter(|option| *option != language)
                                .map(|option| view! {
                                    <option value=key(option) selected=edit_as.get_untracked() == Some(option)>
                                        {option.label()}
                                    </option>
                                })
                                .collect_view()}
                        </select>
                    </label>
                    <label class="demo__picker">
                        "Sample"
                        <select
                            class="demo__select demo__sample-select"
                            aria-label="Sample config"
                            on:change=move |event| navigate_with("sample", &event_target_value(&event))
                        >
                            <option value="small" selected=!large_sample>"Short"</option>
                            <option value="large" selected=large_sample>"Large (~2000 lines)"</option>
                        </select>
                    </label>
                    <label class="demo__picker">
                        "Theme"
                        <select
                            class="demo__select demo__theme-select"
                            aria-label="Editor theme"
                            on:change=move |event| {
                                theme.set(event_target_value(&event).parse().unwrap_or_default());
                            }
                        >
                            {EditorTheme::ALL
                                .iter()
                                .map(|option| view! {
                                    <option value=option.as_str()>{option.label()}</option>
                                })
                                .collect_view()}
                        </select>
                    </label>
                    <button
                        class="config-editor__action-button"
                        type="button"
                        disabled=move || baseline.with(|baseline| saved.with(|saved| baseline == saved))
                        on:click=move |_| baseline.set(saved.get())
                    >
                        "Apply changes"
                    </button>
                </ConfigEditorToolbar>
                <ConfigEditor
                    language=language
                    edit_as=edit_as
                    initial_value=sample
                    baseline=baseline
                    value=saved
                    on_change=move |text| saved.set(text)
                    on_edit_as_change=move |edit| editing.set(edit)
                    schema=schema
                    on_schema_warning=move |warning| schema_warnings.update(|all| all.push(warning))
                    file_name=file_name
                    theme=theme
                    read_only=read_only
                    show_toolbar=false
                    show_footer=true
                />
                <ul class="demo__schema-warnings">
                    {move || schema_warnings.get().into_iter().map(|warning| view! { <li>{warning}</li> }).collect_view()}
                </ul>
                <details class="demo__output">
                    <summary>{format!("Saved value ({language}) — what on_change sends the host")}</summary>
                    <pre class="demo__output-text">{move || saved.get()}</pre>
                </details>
            </div>
        }
    })
}
